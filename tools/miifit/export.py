"""Writes the runtime's esports_miis.inc: the fitted Miis (RFLCharData, name left to the runtime) by
Toad's Factory picture file (the player's own Mii from Retro WFC where it renders as the picture,
rwfc.py), and each country's middle (where the globe turns) and name."""
import json
import os
import sys
import zlib

import rwfc
import studio

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, '..', '..', 'sandbox-rankings', 'BuildWorkspace', 'runtime', 'src', 'esports_miis.inc')


def main(out=DEFAULT_OUT):
    # only the Grand Star Cup's players (gsc_players.py): the only ones the game shows
    gsc = {p['mii'] for p in json.load(open(os.path.join(HERE, 'gsc_players.json'), encoding='utf-8'))}
    fits = json.load(open(os.path.join(HERE, 'fits.json')))
    old = os.path.join(HERE, 'fits_old.json')   # the earlier fits where these aren't refitted yet
    fits = {f: v for f, v in dict(json.load(open(old)) if os.path.exists(old) else {}, **fits).items() if f in gsc}
    countries = json.load(open(os.path.join(HERE, 'countries.json')))
    names = json.load(open(os.path.join(HERE, 'country_names.json'), encoding='utf-8'))
    path = os.path.join(HERE, 'rwfc.json')
    exact = {f: r for f, r in (json.load(open(path)) if os.path.exists(path) else {}).items() if r['error'] < rwfc.SAME and f in gsc}
    lines = [
        '// Generated by tools/miifit/export.py: do not edit.',
        '// Wii Miis fitted to Toad\'s Factory\'s Mii pictures (tools/miifit; the players\' own from Retro WFC',
        '// where they render as the picture), RFLCharData without the name (the runtime\'s),',
        '// by picture file; and each country\'s middle (ISO 3166 code, latitude, longitude in degrees) and name.',
        'struct EsFittedMiiEntry {',
        '    const char* file;',
        '    const char* data;   // 0x4A bytes, hex',
        '};',
        'const EsFittedMiiEntry kEsFittedMiis[] = {',
    ]
    for file in sorted(set(fits) | set(exact)):
        if file in exact:
            data = exact[file]['data']
        else:
            data = studio.char_data(fits[file]['mii'], zlib.crc32(file.encode()) & 0x1FFFFFFF).hex()
        lines.append(f'    {{"{file}", "{data}"}},')
    lines += [
        '};',
        'struct EsCountryPlace {',
        '    const char* iso;',
        '    float latitude, longitude;',
        '    const char* name;',
        '};',
        'const EsCountryPlace kEsCountryPlaces[] = {',
    ]
    for iso in sorted(countries):
        lat, lon = countries[iso]
        name = names[iso].replace('"', "'")
        lines.append(f'    {{"{iso}", {lat:.3f}f, {lon:.3f}f, "{name}"}},')
    lines.append('};')
    open(out, 'w', newline='\r\n', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(len(set(fits) | set(exact)), 'Miis,', len(exact), 'from Retro WFC,', len(countries), 'countries ->', os.path.normpath(out))


if __name__ == '__main__':
    main(*sys.argv[1:])
